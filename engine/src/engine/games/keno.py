"""``originals.keno`` — the provably-fair Keno Original (spec §A.8).

Pick 1–10 numbers from a **1–40** grid; ``sampleWithoutReplacement(40, 10)`` draws
10 distinct numbers from the seeded stream; the payout multiplier is read from a
per-``(picks, risk)`` table indexed by the number of ``hits`` (picks ∩ drawn).

**Hit distribution is hypergeometric** (spec §A.8):

    P(hits = h | picks = k) = C(k, h) · C(40 - k, 10 - h) / C(40, 10)

Each ``(picks, risk)`` payout vector ``{pay_h}`` is **TUNED** so the analytic RTP
``Σ_h P(h) · pay_h = 1 - edge`` to within ±0.2% *after* rounding each multiplier to
two decimals — verified independently for all 30 cells by ``tests/test_keno_rtp.py``
(the in-repo proof). The tables are published DATA in ``GameConfig.params["tables"]``
(configurable, DB-authoritative at runtime); :data:`DEFAULT_TABLES` is the engine
seed/default, never a literal inside :meth:`Keno.play` (the table is config, not code).

**Tuning method** (reproducible, for the record — the numbers are guarded by the
analytic test, not regenerated at runtime). For each ``(picks k, risk)``:

* the first paying hit-count ``t = clamp(mode(k) + offset, 1, k)`` where
  ``mode(k) = floor((k+1)·11 / 42)`` is the hypergeometric mode, and ``offset`` is
  ``{LOW: 0, MEDIUM: 1, HIGH: 2}`` — higher risk pays only on rarer (higher) hits;
* a **geometric** shape ``pay_h ∝ g^(h - t)`` over the winning tail ``h ∈ [t, k]``
  with ratio ``g`` ``{LOW: 3.0, MEDIUM: 4.0, HIGH: 6.0}`` (the volatility knob) keeps
  payouts monotonically increasing in hits and the top prize realistic;
* the shape is scaled so ``Σ P(h)·pay_h = 1 - edge``, rounded to two decimals, then
  a few single-cent adjustments (largest-effect-first) drive the post-rounding RTP
  back onto target — the table is OPTIMIZED to hit target; outcomes are NEVER clamped
  and no tolerance is loosened.

Pure: stdlib only (``math.comb`` is used only by the test, not here); entropy enters
solely via the injected ``RngStream``; the table + ``edge`` are read from ``cfg``. The
same ``(server_seed, client_seed, nonce)`` + ``input`` always yields the same draw and
multiplier — server == verifier by construction.
"""

