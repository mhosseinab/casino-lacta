def default_params() -> dict[str, Any]:
    """The engine seed/default ``GameConfig.params`` for keno — JSON-friendly.

    Shapes :data:`DEFAULT_TABLES` into ``{"tables": {risk: {str(picks): [pay_h]}}}``
    (string picks keys so it round-trips through JSON / the DB ``GameConfig`` row).
    DB ``GameConfig.params`` is authoritative at runtime; this is the seed value.
    """
    return {
        "tables": {
            risk: {str(picks): list(pays) for picks, pays in by_picks.items()}
            for risk, by_picks in DEFAULT_TABLES.items()
        }
    }


@dataclass(frozen=True)
class Keno:
    """Conforms to ``engine.types.InstantGame`` (spec §A.8)."""

    id: str = "originals.keno"

    def validate_input(self, input: dict[str, Any], cfg: GameConfig) -> None:
        """Reject malformed / out-of-band keno input BEFORE any money moves (pure).

        ``picks`` must be a list/tuple of 1–10 DISTINCT integers, each in [1, 40];
        ``risk`` (default ``MEDIUM``) must be one of LOW/MEDIUM/HIGH. This is the
        COMPLETE fence — passing it guarantees :meth:`play` cannot raise on this
        input (a valid ``(risk, |picks|)`` always resolves a table row).
        """
        if "picks" not in input:
            raise InvalidBetInput("keno requires 'picks'")
        picks = input["picks"]
        if not isinstance(picks, (list, tuple)):
            raise InvalidBetInput(f"keno 'picks' must be a list, got {type(picks).__name__}")
        if not (1 <= len(picks) <= _MAX_PICKS):
            raise InvalidBetInput(
                f"keno 'picks' must have 1..{_MAX_PICKS} numbers, got {len(picks)}"
            )
        for p in picks:
            # bool is a subclass of int — reject it explicitly so True/False can't
            # masquerade as 1/0.
            if not isinstance(p, int) or isinstance(p, bool):
                raise InvalidBetInput(f"keno 'picks' must be integers, got {p!r}")
            if not (_GRID_LO <= p <= _GRID_HI):
                raise InvalidBetInput(
                    f"keno pick {p} out of range [{_GRID_LO}, {_GRID_HI}]"
                )
        if len(set(picks)) != len(picks):
            raise InvalidBetInput(f"keno 'picks' must be distinct, got {list(picks)}")
        risk = str(input.get("risk", _DEFAULT_RISK)).upper()
        if risk not in _RISKS:
            raise InvalidBetInput(
                f"keno 'risk' must be one of {_RISKS}, got {risk!r}"
            )

    def play(self, input: dict[str, Any], rng: RngStream, cfg: GameConfig) -> Outcome:
        """Resolve one keno bet — pure function of (input, rng stream, cfg).

        Draws 10 distinct numbers from the 1–40 grid (consuming exactly 10 draws,
        regardless of ``|picks|``), counts ``hits = |picks ∩ drawn|``, and looks up
        the multiplier from the tuned ``cfg.params["tables"][risk][picks]`` vector.
        """
        picks = list(input["picks"])
        risk = str(input.get("risk", _DEFAULT_RISK)).upper()

        drawn = sample_without_replacement(rng, _GRID, _DRAW_COUNT)
        hits = len(set(picks) & set(drawn))

        table = cfg.params["tables"][risk][str(len(picks))]
        multiplier = float(table[hits])

        return Outcome(
            multiplier=multiplier,
            detail={
                "drawn": list(drawn),
                "hits": hits,
                "picks": picks,
                "risk": risk,
            },
        )


# The module-level singleton the registry resolves (see engine.games.__init__).
GAME = Keno()
